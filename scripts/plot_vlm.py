import csv
import getopt
import math
from pathlib import Path
import sys


def number(value):
    try:
        result = float(value)
        return result if math.isfinite(result) else None
    except (ValueError, TypeError):
        return None


def boolean(value):
    return {'true': 1.0, 'false': 0.0}.get(str(value).lower())


def read_rows(path):
    with path.open(newline='') as stream:
        reader = csv.DictReader(stream)
        required = {'condition', 'true_a', 'true_b', 'predicted_a', 'predicted_b',
                    'true_difference_b_minus_a', 'predicted_difference_b_minus_a',
                    'true_ratio_b_over_a', 'predicted_ratio_b_over_a',
                    'true_b_greater_a', 'predicted_b_greater_a'}
        if not required.issubset(reader.fieldnames or []):
            raise ValueError('Input must be an evaluation.csv generated by run_vlm.py')
        rows = list(reader)
    if not rows:
        raise ValueError('CSV is empty')
    for key in ('true_a', 'true_b', 'units'):
        if len({r.get(key, '') for r in rows}) != 1:
            raise ValueError('Use a CSV for a single image/reference, not concatenated runs')
    return rows


def plot(path, output):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import numpy as np

    rows = read_rows(path)
    intact = [r for r in rows if r['condition'] == 'intact']
    if not intact:
        raise ValueError('No intact readings to plot')
    colors = {'intact': '#2563eb', 'direct': '#159477'}
    names = {'intact': 'Calculated from A/B', 'direct': 'Direct answers'}
    plt.rcParams.update({'font.size': 10, 'axes.spines.top': False,
                         'axes.spines.right': False, 'figure.facecolor': 'white'})
    fig, axes = plt.subplots(2, 3, figsize=(15, 8.5), constrained_layout=True)
    units = rows[0].get('units', '')
    for ax, label in zip(axes[0, :2], ('a', 'b')):
        values = [number(r['predicted_' + label]) for r in intact]
        truth = number(rows[0]['true_' + label])
        if truth is None:
            raise ValueError('Missing reference value')
        ax.scatter(range(1, len(values)+1), [np.nan if v is None else v for v in values],
                   color=colors['intact'], s=32, label='VLM reading')
        ax.axhline(truth, color='#111827', linestyle='--', label=f'Reference: {truth:.3f}')
        ax.set(title=f'{label.upper()}: predicted and reference values', xlabel='Reading number', ylabel=units)
        ax.legend(fontsize=9)
    pairs = [(number(r['predicted_a']), number(r['predicted_b'])) for r in intact]
    pairs = [p for p in pairs if None not in p]
    if pairs:
        unique, counts = np.unique(pairs, axis=0, return_counts=True)
        axes[0,2].scatter(unique[:,0], unique[:,1], s=counts*35, alpha=.65, color=colors['intact'])
        for (a,b), count in zip(unique, counts):
            axes[0,2].annotate(str(count), (a,b), xytext=(7,5), textcoords='offset points', fontsize=9)
    axes[0,2].scatter([float(rows[0]['true_a'])], [float(rows[0]['true_b'])],
                      color='black', marker='*', s=160, label='Reference pair')
    axes[0,2].set(title='Paired readings (numbers = frequency)', xlabel=f'A ({units})', ylabel=f'B ({units})')
    axes[0,2].legend(fontsize=9)

    summary = []
    queries = [('difference', 'difference_b_minus_a', units),
               ('ratio', 'ratio_b_over_a', 'dimensionless'),
               ('ordering', 'b_greater_a', '')]
    for ax, (query, suffix, unit) in zip(axes[1], queries):
        convert = boolean if query == 'ordering' else number
        truth = convert(rows[0]['true_' + suffix])
        heights, ticks, bar_colors = [], [], []
        for condition in colors:
            candidates = [r for r in rows if r['condition'] == condition and
                          (condition != 'direct' or r.get('query') == query)]
            if not candidates:
                continue
            valid = []
            for row in candidates:
                if condition == 'direct' and row.get('valid', '').lower() == 'false':
                    continue
                if query == 'ratio' and row.get('predicted_ratio_valid', '').lower() == 'false':
                    continue
                value = convert(row['predicted_' + suffix])
                if value is not None:
                    valid.append(value)
            score = None
            if truth is not None and valid:
                score = (sum(valid)/len(valid)-truth)**2 if query == 'ordering' else sum(abs(v-truth) for v in valid)/len(valid)
                heights.append(score); ticks.append(names[condition] + f'\nn={len(valid)}'); bar_colors.append(colors[condition])
            summary.append(dict(query=query, condition=condition, reference=truth,
                                valid_rows=len(valid), excluded_rows=len(candidates)-len(valid),
                                predicted_mean=sum(valid)/len(valid) if valid else None,
                                metric='Brier score' if query == 'ordering' else 'Mean absolute error', score=score))
        if heights:
            bars = ax.bar(ticks, heights, color=bar_colors, width=.6)
            ax.bar_label(bars, fmt='%.3f', padding=4)
            ax.set_ylim(0, max(max(heights)*1.25, .05))
        else:
            ax.text(.5,.5,'No scorable answers',ha='center',transform=ax.transAxes)
        ax.set(title={'difference':'Difference B − A', 'ratio':'Ratio B / A', 'ordering':'Ordering B > A'}[query],
               ylabel='Brier score (lower is better)' if query == 'ordering' else f'Mean absolute error ({unit})')
        ax.tick_params(axis='x', labelsize=9)
    direct_note = 'Direct answers included where available.' if any(r['condition']=='direct' for r in rows) else 'Direct VLM relationship answers were not collected.'
    fig.suptitle(f'VLM pilot · {len(intact)} paired readings · {path.parent.name}\n'
                 f'{direct_note}\nEach relationship uses one trial; no cross-trial recombination.', fontsize=13)
    output.mkdir(parents=True, exist_ok=True)
    for extension in ('png','pdf'):
        fig.savefig(output / ('performance.' + extension), dpi=180)
    plt.close(fig)
    value_fig, value_axes = plt.subplots(1, 3, figsize=(15, 4.8), constrained_layout=True)
    for ax, (query, suffix, unit) in zip(value_axes, queries):
        entries = [entry for entry in summary if entry['query'] == query]
        convert = boolean if query == 'ordering' else number
        truth = convert(rows[0]['true_' + suffix])
        heights, ticks, palette = [], [], []
        if truth is not None:
            heights.append(truth); ticks.append('Ground truth'); palette.append('#374151')
        for entry in entries:
            if entry['predicted_mean'] is not None:
                heights.append(entry['predicted_mean'])
                ticks.append(names[entry['condition']])
                palette.append(colors[entry['condition']])
        if heights:
            bars = ax.bar(ticks, heights, color=palette, width=.6)
            ax.bar_label(bars, fmt='%.3f', padding=4)
            low, high = min(0, min(heights)), max(0, max(heights))
            padding = max(high-low, .1)*.2
            ax.set_ylim(low-padding if low < 0 else 0, high+padding)
            ax.axhline(0, color='#9ca3af', linewidth=.6)
        if truth is None:
            ax.text(.5,.95,'Ground truth undefined', ha='center', va='top', transform=ax.transAxes)
        ax.set(title={'difference':'Difference B − A', 'ratio':'Ratio B / A',
                      'ordering':'Ordering B > A'}[query],
               ylabel='Fraction predicting true (reference: 0 or 1)' if query == 'ordering'
                      else f'Mean predicted value / reference ({unit})')
        ax.tick_params(axis='x', labelsize=9)
    value_fig.suptitle('Relationship predictions compared with ground truth\n'
                      'Numerical bars show means; ordering bars show fractions of true answers.\n'
                      + direct_note, fontsize=12)
    for extension in ('png', 'pdf'):
        value_fig.savefig(output / ('relationships.' + extension), dpi=180)
    plt.close(value_fig)
    dist_fig, dist_axes = plt.subplots(1, 3, figsize=(15, 4.8), constrained_layout=True)
    for ax, (query, suffix, unit) in zip(dist_axes, queries):
        convert = boolean if query == 'ordering' else number
        truth = convert(rows[0]['true_' + suffix])
        for offset, condition in enumerate(colors):
            values = []
            for row in rows:
                if row['condition'] != condition:
                    continue
                if condition == 'direct' and (row.get('query') != query or row.get('valid', '').lower() == 'false'):
                    continue
                if query == 'ratio' and row.get('predicted_ratio_valid', '').lower() == 'false':
                    continue
                value = convert(row['predicted_' + suffix])
                if value is not None:
                    values.append(value)
            if not values:
                ax.text(.02, .95-offset*.07, f'{names[condition]}: no valid trials',
                        transform=ax.transAxes, va='top', fontsize=9)
                continue
            label = f'{names[condition]} (n={len(values)})'
            if query == 'ordering':
                probabilities = [values.count(0.)/len(values), values.count(1.)/len(values)]
                ax.bar(np.array([0,1])+(offset-.5)*.32, probabilities, width=.32,
                       color=colors[condition], label=label)
            else:
                unique, counts = np.unique(values, return_counts=True)
                cdf = np.cumsum(counts)/len(values)
                ax.step(np.r_[unique[0], unique], np.r_[0., cdf], where='post',
                        color=colors[condition], label=label)
                ax.scatter(unique, cdf, color=colors[condition], s=12)
        if truth is not None:
            ax.axvline(truth, color='black', linestyle='--', label=f'Ground truth: {truth:.4g}')
        if query == 'ordering':
            ax.set_xticks([0,1], ['False', 'True'])
        ax.set(title={'difference':'B − A distribution', 'ratio':'B / A distribution',
                      'ordering':'B > A distribution'}[query],
               xlabel='Answer' if query == 'ordering' else f'Value ({unit})',
               ylabel='Probability' if query == 'ordering' else 'Cumulative fraction of valid trials',
               ylim=(0, 1.08))
        ax.legend(fontsize=8)
    dist_fig.suptitle('Direct versus calculated relationship distributions\n'
                      'Empirical variation across trials, not calibrated uncertainty.', fontsize=12)
    for extension in ('png', 'pdf'):
        dist_fig.savefig(output / ('distributions.' + extension), dpi=180)
    plt.close(dist_fig)
    with (output/'plot_summary.csv').open('w', newline='') as stream:
        writer=csv.DictWriter(stream, fieldnames=list(summary[0]))
        writer.writeheader(); writer.writerows(summary)
    print(f'Saved distribution, performance and relationships plots (PNG/PDF), and plot_summary.csv to {output}')


def plot_random_pairs(path, output):
    """Plot each pair separately from evaluate_random_pairs.py's trial_errors.csv."""
    from collections import Counter, defaultdict
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.backends.backend_pdf import PdfPages

    with path.open(newline='') as stream:
        reader = csv.DictReader(stream)
        required = {'example_id', 'map_id', 'experiment', 'trial', 'query',
                    'truth', 'prediction', 'valid'}
        if not required.issubset(reader.fieldnames or []):
            raise ValueError('Expected random-pair trial_errors.csv')
        rows = list(reader)
    if not rows:
        raise ValueError('CSV is empty')
    groups = defaultdict(list)
    seen = set()
    for row in rows:
        if row['experiment'] not in ('verbose', 'non-verbose') or row['query'] not in ('difference', 'ratio', 'ordering'):
            raise ValueError('Unknown experiment or query')
        key = (row['example_id'], row['experiment'], row['trial'], row['query'])
        if key in seen:
            raise ValueError('Duplicate trial: ' + str(key))
        seen.add(key)
        # IDs become filenames; do not allow paths supplied through the CSV.
        for field in ('map_id', 'example_id'):
            if not row[field] or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_' for c in row[field]):
                raise ValueError('Unsafe or empty identifier')
        groups[(row['map_id'], row['example_id'])].append(row)
    for pair_rows in groups.values():
        for query in ('difference', 'ratio', 'ordering'):
            subset = [r for r in pair_rows if r['query'] == query]
            if len({r['truth'] for r in subset}) > 1:
                raise ValueError('Conflicting references within a pair')
            for row in subset:
                value = number(row['prediction'])
                if row['valid'].lower() not in ('true', 'false'):
                    raise ValueError('Invalid validity flag')
                if row['valid'].lower() == 'true' and (value is None or number(row['truth']) is None
                        or (query == 'ordering' and value not in (0., 1.))):
                    raise ValueError('Invalid value marked valid')

    output.mkdir(parents=True, exist_ok=True)
    names = {'verbose': 'Calculated from A/B', 'non-verbose': 'Direct answers'}
    colors = {'verbose': '#2563eb', 'non-verbose': '#159477'}
    titles = {'difference': 'A − B', 'ratio': 'A / B', 'ordering': 'A > B'}
    distribution_rows = []
    maps = sorted({mid for mid, _ in groups})
    for mid in maps:
        map_output = output / mid
        map_output.mkdir(exist_ok=True)
        with PdfPages(output / (mid + '.pdf')) as pdf:
            for map_id, example_id in sorted(groups):
                if map_id != mid:
                    continue
                pair_rows = groups[(map_id, example_id)]
                fig, axes = plt.subplots(1, 3, figsize=(15, 4.8), constrained_layout=True)
                for ax, query in zip(axes, ('difference', 'ratio', 'ordering')):
                    subset = [r for r in pair_rows if r['query'] == query]
                    truth = number(subset[0]['truth']) if subset else None
                    for offset, method in enumerate(names):
                        attempts = [r for r in subset if r['experiment'] == method]
                        values = [number(r['prediction']) for r in attempts if r['valid'].lower() == 'true']
                        counts = Counter(values)
                        excluded = len(attempts) - len(values)
                        label = f'{names[method]}: {len(values)}/{len(attempts)} valid'
                        if len(values) == 1:
                            label += ' (one valid trial)'
                        if values:
                            if query == 'ordering':
                                ax.bar([x + (offset-.5)*.34 for x in (0, 1)],
                                       [counts[x]/len(values) for x in (0., 1.)],
                                       width=.34, color=colors[method], label=label)
                            else:
                                xs = sorted(counts)
                                cumulative = []
                                total = 0
                                for x in xs:
                                    total += counts[x]
                                    cumulative.append(total/len(values))
                                ax.step([xs[0]] + xs, [0.] + cumulative, where='post',
                                        color=colors[method], label=label)
                                ax.scatter(xs, cumulative, color=colors[method], s=18)
                        else:
                            ax.plot([], [], color=colors[method], label=label)
                        support = (0., 1.) if query == 'ordering' and values else sorted(counts)
                        for value in support or [None]:
                            distribution_rows.append(dict(map_id=mid, example_id=example_id,
                                experiment=method, query=query, reference=truth, value=value,
                                count=counts[value] if value is not None else 0,
                                probability=counts[value]/len(values) if values else None,
                                valid_count=len(values), excluded_count=excluded,
                                attempted_count=len(attempts)))
                    if truth is not None:
                        ax.axvline(truth, color='black', linestyle='--', label=f'Ground truth: {truth:.4g}')
                    else:
                        ax.text(.02, .55, 'Ground truth undefined or missing', transform=ax.transAxes, fontsize=9)
                    if query == 'ordering':
                        ax.set_xticks([0, 1], ['False', 'True'])
                        ax.set_xlim(-.5, 1.5)
                    ax.set(title=titles[query], ylim=(0, 1.08),
                           xlabel={'difference': 'Value (map legend units)', 'ratio': 'Value (dimensionless)',
                                   'ordering': 'Answer'}[query],
                           ylabel='Probability' if query == 'ordering' else 'Cumulative fraction of valid trials')
                    ax.legend(fontsize=8, loc='best')
                    ax.spines[['top', 'right']].set_visible(False)
                fig.suptitle(example_id + '\nEmpirical trial distributions; not calibrated uncertainty. '
                             'Excluded answers are omitted; different pairs are not pooled.', fontsize=11)
                fig.savefig(map_output / (example_id + '.png'), dpi=140)
                pdf.savefig(fig)
                plt.close(fig)
    with (output / 'distributions.csv').open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(distribution_rows[0]))
        writer.writeheader()
        writer.writerows(distribution_rows)
    print(f'Saved {len(groups)} pair plots, {len(maps)} map PDFs, and distributions.csv to {output}')


def plot_map_metrics(path, output):
    """Plot evaluator summaries without recomputing tests or pooling map units."""
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.backends.backend_pdf import PdfPages

    with path.open(newline='') as stream:
        reader = csv.DictReader(stream)
        fields = reader.fieldnames
        required = {'map_id', 'experiment', 'query', 'expected_pairs', 'scored_pairs',
                    'mean_absolute_error', 'accuracy', 'test_correct', 'test_pairs',
                    'binomial_p_value', 'holm_p_value', 'test_status'}
        if not required.issubset(fields or []):
            raise ValueError('Expected per_map_metrics.csv from evaluate_random_pairs.py')
        rows = list(reader)
    if not rows:
        raise ValueError('CSV is empty')
    groups = {}
    seen = set()
    for row in rows:
        mid = row['map_id']
        if not mid or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_' for c in mid):
            raise ValueError('Unsafe or empty map identifier')
        key = (mid, row['experiment'], row['query'])
        if key in seen:
            raise ValueError('Duplicate map/experiment/query summary')
        seen.add(key)
        if row['experiment'] not in ('verbose', 'non-verbose') or row['query'] not in ('difference', 'ratio', 'ordering'):
            raise ValueError('Unknown experiment or query')
        for column in ('mean_absolute_error', 'accuracy', 'binomial_p_value', 'holm_p_value'):
            if row[column] != '':
                value = number(row[column])
                if value is None or value < 0 or (column != 'mean_absolute_error' and value > 1):
                    raise ValueError('Invalid summary value: ' + column)
        groups.setdefault(mid, {})[(row['experiment'], row['query'])] = row
    output.mkdir(parents=True, exist_ok=True)
    names = {'verbose': 'Verbose\nCalculated from A and B', 'non-verbose': 'Non-verbose\nDirect answers'}
    colors = {'verbose': '#2563eb', 'non-verbose': '#159477'}
    with PdfPages(output/'per_map_metrics.pdf') as pdf:
        for mid, group in groups.items():
            fig, axes = plt.subplots(2, 2, figsize=(12, 9), constrained_layout=True)
            methods = [m for m in names if any(k[0] == m for k in group)]
            for ax, query in zip(axes[0], ('difference', 'ratio')):
                ax.set_xticks(range(len(methods)), [names[m] for m in methods])
                ax.set_xlim(-.6, len(methods)-.4)
                for x, method in enumerate(methods):
                    row = group.get((method, query), {})
                    value = number(row.get('mean_absolute_error'))
                    if value is None:
                        ax.text(x, .05, 'No scorable answers', ha='center', transform=ax.get_xaxis_transform(), fontsize=9)
                    else:
                        ax.bar(x, value, color=colors[method], width=.55)
                        ax.annotate(f'{value:.4g}\n{row["scored_pairs"]}/{row["expected_pairs"]} pairs',
                                    (x, value), xytext=(0, 5), textcoords='offset points', ha='center', fontsize=9)
                ax.axhline(0, color='black', linewidth=.8)
                ax.set_ylim(0, max([number(group.get((m, query), {}).get('mean_absolute_error')) or 0 for m in methods]+[.01])*1.35)
                ax.set(title='A − B: mean absolute error' if query=='difference' else 'A / B: mean absolute error',
                       ylabel='Map legend units; ideal error = 0' if query=='difference' else 'Dimensionless; ideal error = 0')
            ax = axes[1, 0]
            for x, method in enumerate(methods):
                row = group.get((method, 'ordering'), {})
                accuracy = number(row.get('accuracy'))
                if accuracy is not None:
                    ax.bar(x, accuracy, color=colors[method], width=.55)
                    ax.text(x, accuracy+.035, f'{row["test_correct"]}/{row["test_pairs"]} correct\n{row["test_status"]}', ha='center', fontsize=9, bbox=dict(facecolor='white', edgecolor='none', alpha=.9))
                else:
                    ax.text(x, .05, 'No tested pairs', ha='center', fontsize=9)
            ax.axhline(1, color='black', linestyle='--', linewidth=1, label='Perfect agreement')
            ax.set_xticks(range(len(methods)), [names[m] for m in methods])
            ax.set(title='A > B: accuracy on the selected trial', ylabel='Fraction correct', ylim=(0, 1.25))
            ax.legend(fontsize=8, loc='upper right')
            ax = axes[1, 1]
            for x, method in enumerate(methods):
                row = group.get((method, 'ordering'), {})
                for offset, column, label, marker in [(-.12,'binomial_p_value','Raw','o'),(.12,'holm_p_value','Holm','s')]:
                    value = number(row.get(column))
                    if value is None:
                        ax.text(x+offset, .03 if offset<0 else .14, f'{label}: unavailable', ha='center', fontsize=8, rotation=15)
                    else:
                        ax.scatter(x+offset, value, color=colors[method], marker=marker, s=65)
                        ax.annotate(f'{label}: {value:.4g}', (x+offset,value), xytext=(0, 7 if offset<0 else -15),
                                    textcoords='offset points', ha='center', fontsize=8)
            ax.set_xticks(range(len(methods)), [names[m] for m in methods])
            ax.set(title='A > B: exact binomial p-values', ylabel='p-value (linear scale)', ylim=(-.08,1.12),
                   xlim=(-.6,len(methods)-.4))
            for axis in axes.flat:
                axis.spines[['top','right']].set_visible(False)
            fig.suptitle(mid+'\nPer-map scores against NetCDF truth; numerical MAE has no p-value.', fontsize=12)
            fig.supxlabel('P-values are shown as stored, without significance labels. Holm scope follows the input evaluation.\n'
                          'Numerical errors exclude unscorable answers; ordering counts invalid attempts as incorrect.', fontsize=9)
            fig.savefig(output/(mid+'-metrics.png'), dpi=160)
            pdf.savefig(fig)
            plt.close(fig)
    with (output/'plotted_metrics.csv').open('w', newline='') as stream:
        writer=csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader(); writer.writerows(rows)
    print(f'Saved {len(groups)} map score plots, per_map_metrics.pdf, and plotted_metrics.csv to {output}')



def plot_overall(path, output, dataset, data):
    """Equal-map ECDFs, with explicit missing scores and numerical coverage."""
    import hashlib
    import json
    import numpy as np
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    manifest = json.loads((dataset/'manifest.json').read_text())
    for name in ('alignment.json', 'numerical.npy'):
        digest = hashlib.sha256((data/name).read_bytes()).hexdigest()
        if digest != manifest['source_sha256'][name]:
            raise ValueError('Dataset source checksum mismatch: '+name)
    metadata = path.parent/'evaluation.json'
    if metadata.exists():
        evaluation = json.loads(metadata.read_text())
        expected = evaluation.get('manifest_sha256')
        if expected and expected != hashlib.sha256((dataset/'manifest.json').read_bytes()).hexdigest():
            raise ValueError('Evaluation dataset checksum mismatch')
    records = json.loads((data/'alignment.json').read_text())['records']
    arrays = np.load(data/'numerical.npy', mmap_mode='r')
    scales = {}
    for example in manifest['examples']:
        mid = example['map_id']
        if mid not in scales:
            index = example['sample']
            values = arrays[index, :records[index]['length']]
            values = values[np.isfinite(values)]
            scales[mid] = float(np.ptp(np.percentile(values, [5,95]))) if len(values) else 0.
    with path.open(newline='') as stream:
        rows = list(csv.DictReader(stream))
    exported = []
    seen = set()
    for row in rows:
        mid, method, query = row['map_id'], row['experiment'], row['query']
        key = (mid,method,query)
        if key in seen or mid not in scales:
            raise ValueError('Duplicate summary or unknown map')
        seen.add(key)
        value = number(row['accuracy'] if query == 'ordering' else row['mean_absolute_error'])
        if query == 'difference':
            value = value/scales[mid] if value is not None and scales[mid]>0 else None
        if query == 'ordering' and row['test_status'] != 'complete':
            value = None
        exported.append(dict(map_id=mid, experiment=method, query=query, score=value,
            normalization_scale=scales[mid] if query=='difference' else '',
            scored_pairs=row['scored_pairs'], expected_pairs=row['expected_pairs']))
    output.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(2,3,figsize=(15,9),constrained_layout=True)
    names={'verbose':'Calculated from A and B','non-verbose':'Direct answers'}
    colors={'verbose':'#2563eb','non-verbose':'#159477'}
    summaries=[]
    for col, query in enumerate(('difference','ratio','ordering')):
        for method in names:
            subset=[r for r in exported if r['query']==query and r['experiment']==method]
            if not subset: continue
            values=sorted(r['score'] for r in subset if r['score'] is not None)
            total=len(scales)
            ax=axes[0,col]
            if values:
                x=np.unique(values)
                y=np.searchsorted(values,x,side='right')/len(values)
                ax.step(np.r_[x[0],x],np.r_[0,y],where='post',color=colors[method],
                        label=f'{names[method]} ({len(values)}/{total} maps)')
                ax.scatter(x,y,s=12,color=colors[method])
            else:
                ax.plot([],[],color=colors[method],label=f'{names[method]} (0/{total} maps)')
            coverage=sorted(int(r['scored_pairs'])/int(r['expected_pairs']) for r in subset if int(r['expected_pairs']))
            if coverage:
                x=np.unique(coverage); y=np.searchsorted(coverage,x,side='right')/len(coverage)
                axes[1,col].step(np.r_[x[0],x],np.r_[0,y],where='post',color=colors[method],label=names[method])
            summaries.append(dict(experiment=method,query=query,scored_maps=len(values),total_maps=total,
                macro_mean=float(np.mean(values)) if values else '',median=float(np.median(values)) if values else '',
                scored_pairs=sum(int(r['scored_pairs']) for r in subset),expected_pairs=sum(int(r['expected_pairs']) for r in subset)))
        axes[0,col].axvline(1 if query=='ordering' else 0,color='black',ls='--',lw=1,label='Perfect score')
        axes[0,col].set_xlabel({'difference':'A − B MAE / map (P95 − P05)','ratio':'A / B MAE','ordering':'A > B accuracy'}[query])
        if query == 'ratio':
            axes[0,col].set_xscale('symlog', linthresh=1)
            axes[0,col].set_xlabel('A / B MAE (linear to 1, logarithmic beyond)')
        axes[0,col].set_title('Ordering: higher is better' if query=='ordering' else 'Numerical error: lower is better')
        axes[1,col].set(xlabel='Scored pairs / all sampled pairs',xlim=(-.03,1.03),title='Scoring coverage')
        for ax in axes[:,col]:
            ax.set(ylabel='Cumulative fraction of maps',ylim=(0,1.05))
            ax.legend(fontsize=8,loc='lower right'); ax.grid(alpha=.2)
    fig.suptitle('Overall performance across maps • each map has equal weight',fontsize=16)
    fig.supxlabel('Numerical scores describe valid answers only; missing scores are excluded, not set to zero.\n'
                  'Coverage includes undefined reference ratios. Curves show variation across maps, not repeat uncertainty.',fontsize=10)
    for suffix in ('png','pdf'): fig.savefig(output/('overall_performance.'+suffix),dpi=170)
    plt.close(fig)
    for name, values in [('overall_per_map.csv',exported),('overall_summary.csv',summaries)]:
        with (output/name).open('w',newline='') as stream:
            writer=csv.DictWriter(stream,fieldnames=list(values[0]));writer.writeheader();writer.writerows(values)
    print('Saved overall performance distributions to',output)


