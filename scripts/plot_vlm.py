    opts, extra = getopt.gnu_getopt(sys.argv[1:] if argv is None else argv, '', ['csv=', 'output=', 'help', 'overall', 'dataset=', 'data='])
    args=dict(opts)
    if '--help' in args:
        print('python plot_vlm.py --csv RUN/evaluation.csv_OR_trial_errors.csv_OR_per_map_metrics.csv [--output DIR] [--overall --dataset DIR --data DIR]')
        return
    if extra or '--csv' not in args:
        raise ValueError('Usage: python plot_vlm.py --csv RUN/evaluation.csv [--output DIR] [--overall --dataset DIR --data DIR]')
    path=Path(args['--csv'])
    with path.open(newline='') as stream:
        fields = next(csv.reader(stream), [])
    output = Path(args.get('--output', path.parent/'plots'))
    if '--overall' in args:
        plot_overall(path, output, Path(args.get('--dataset','experiments/random-pairs')),
                     Path(args.get('--data','data/ilamb-gridded-v2')))
        return
    if 'map_id' in fields and 'mean_absolute_error' in fields:
        plot_map_metrics(path, output)
    elif 'example_id' in fields and 'query' in fields:
        plot_random_pairs(path, output)
        metrics = path.parent/'per_map_metrics.csv'
        if metrics.exists():
            plot_map_metrics(metrics, output/'metrics')
    else:
        plot(path, output)


